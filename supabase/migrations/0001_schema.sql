create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- true when the calling user is listed in public.admins (used by RLS + RPCs)
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as
$$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

create table if not exists public.categories (
  name text primary key,
  sort int not null default 0
);

create table if not exists public.branches (
  name text primary key,
  sort int not null default 0,
  active boolean not null default true
);

create table if not exists public.products (
  id int generated by default as identity primary key,
  slug text unique not null,
  name text not null check (char_length(name) between 2 and 200),
  description text not null default '',
  category text not null references public.categories(name) on update cascade,
  price numeric(10,2) not null check (price > 0),
  old_price numeric(10,2) check (old_price is null or old_price > 0),
  stock int not null default 0 check (stock >= 0),
  colors jsonb not null default '[]'::jsonb check (jsonb_typeof(colors) = 'array'),
  sizes  jsonb not null default '[]'::jsonb check (jsonb_typeof(sizes)  = 'array'),
  image text,                       -- key of a bundled image (assets/products/<key>.webp) OR a full https:// URL (Storage)
  active boolean not null default true,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text,
  phone text check (phone is null or phone ~ '^01[0125][0-9]{8}$'),
  addresses jsonb not null default '[]'::jsonb check (jsonb_typeof(addresses) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.coupons (
  code text primary key check (code = upper(code) and code ~ '^[A-Z0-9_-]{3,24}$'),
  percent int not null check (percent between 1 and 100),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no bigint generated always as identity (start with 1001) unique,
  user_id uuid references auth.users(id) on delete set null,   -- kept (null) when a customer deletes the account
  customer_name text not null check (char_length(customer_name) between 3 and 80),
  customer_phone text not null check (customer_phone ~ '^01[0125][0-9]{8}$'),
  customer_email text,
  governorate text,
  address text,
  notes text check (notes is null or char_length(notes) <= 500),
  branch text not null references public.branches(name) on update cascade,
  payment_method text not null check (payment_method in ('InstaPay','فودافون كاش','أورنج كاش','e& money','فوري')),
  coupon_code text,
  discount_percent int not null default 0 check (discount_percent between 0 and 100),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'new' check (status in ('new','preparing','contacted','confirmed','delivered','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders(user_id, created_at desc);
create index if not exists orders_status_idx on public.orders(status, created_at desc);

create table if not exists public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id int references public.products(id) on delete set null,
  product_name text not null,           -- snapshot at order time
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity int not null check (quantity between 1 and 100),
  color text,
  size text
);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- every status change (who + when) for tracking and audit
create table if not exists public.order_events (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null,
  note text,
  actor uuid,                           -- auth.uid() of the person who made the change
  created_at timestamptz not null default now()
);
create index if not exists order_events_order_idx on public.order_events(order_id, created_at);

-- log of customer contact attempts made from the admin page (whatsapp / email)
create table if not exists public.order_messages (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  channel text not null check (channel in ('whatsapp','email')),
  body text,
  sent_by uuid,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated always as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text not null check (char_length(name) between 2 and 80),
  phone text not null check (phone ~ '^01[0125][0-9]{8}$'),
  email text,
  topic text not null check (char_length(topic) between 1 and 80),
  message text not null check (char_length(message) between 5 and 2000),
  created_at timestamptz not null default now()
);

-- ---------- triggers ----------
create or replace function public.touch_updated_at() returns trigger language plpgsql as
$$ begin new.updated_at = now(); return new; end $$;

drop trigger if exists trg_products_touch on public.products;
create trigger trg_products_touch before update on public.products for each row execute function public.touch_updated_at();
drop trigger if exists trg_profiles_touch on public.profiles;
create trigger trg_profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
drop trigger if exists trg_orders_touch on public.orders;
create trigger trg_orders_touch before update on public.orders for each row execute function public.touch_updated_at();

-- create the profile row automatically when someone signs up (Google or email OTP)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as
$$
declare ph text := regexp_replace(coalesce(new.raw_user_meta_data->>'phone',''), '\D', '', 'g');
begin
  if ph ~ '^20' then ph := '0' || substr(ph, 3); end if;
  insert into public.profiles (id, full_name, email, phone)
  values (new.id,
          left(coalesce(nullif(new.raw_user_meta_data->>'full_name',''), nullif(new.raw_user_meta_data->>'name',''), split_part(coalesce(new.email,''),'@',1)), 80),
          new.email,
          case when ph ~ '^01[0125][0-9]{8}$' then ph else null end)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
